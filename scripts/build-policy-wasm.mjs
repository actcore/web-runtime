// MANUAL regen step — only run this when the Rust act-policy kernel changes.
// Requires wasm-pack on PATH plus the wasm32-unknown-unknown target. Builds
// act-policy-wasm and vendors the glue + base64-inlined bytes into
// src/policy/wasm/, committing fresh source inputs for the default build.
// The default `npm run build` does NOT invoke this script — it uses the
// already-committed vendored files under src/policy/wasm/ and copies the
// glue into dist/ via scripts/copy-wasm-glue.mjs (toolchain-free). Run from
// web-runtime/.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const crate = join(here, '../../act-cli/crates/act-policy-wasm');
const outDir = join(here, '../src/policy/wasm');
const distOutDir = join(here, '../dist/policy/wasm');
mkdirSync(outDir, { recursive: true });

// --target web => init(input) accepts a BufferSource (works in Node and browser).
// PATH ('.') must come before the trailing cargo pass-through options —
// wasm-pack's CLI treats an unrecognized flag (--no-default-features) as the
// start of the EXTRA_OPTIONS... catch-all, and anything after gets forwarded
// verbatim to `cargo build`, including a stray positional PATH.
execFileSync(
  'wasm-pack',
  ['build', '--release', '--target', 'web', '--out-dir', 'pkg', '.', '--no-default-features'],
  { cwd: crate, stdio: 'inherit' },
);

const pkg = join(crate, 'pkg');
copyFileSync(join(pkg, 'act_policy_wasm.js'), join(outDir, 'act_policy_wasm.js'));
copyFileSync(join(pkg, 'act_policy_wasm.d.ts'), join(outDir, 'act_policy_wasm.d.ts'));

// KNOWN GOTCHA: tsc only compiles .ts sources — it never copies plain .js
// files from src/ to dist/. dist/policy/kernel.js imports
// ./wasm/act_policy_wasm.js at runtime, so vendor the glue into dist/ too
// (mkdir -p first; dist/ may not exist yet on a clean checkout). This makes
// `npm run build` self-sufficient regardless of whether it runs before or
// after `tsc` in the npm script.
mkdirSync(distOutDir, { recursive: true });
copyFileSync(join(pkg, 'act_policy_wasm.js'), join(distOutDir, 'act_policy_wasm.js'));

const wasm = readFileSync(join(pkg, 'act_policy_wasm_bg.wasm'));
const b64 = wasm.toString('base64');
writeFileSync(
  join(outDir, 'inline.ts'),
  `// GENERATED by scripts/build-policy-wasm.mjs — do not edit.\n` +
    `const B64 =\n  '${b64}';\n` +
    `export const WASM_BYTES: Uint8Array = Uint8Array.from(atob(B64), (c) => c.charCodeAt(0));\n`,
);
console.log(`vendored act-policy-wasm (${wasm.length} bytes) into ${outDir}`);
